export const launchArticleCards: HomeCard[] = launchArticleSpecs.map((article) => ({
  title: article.h1,
  description: article.description,
  href: `/articles/${article.slug}/`,
  cta: 'Читать статью',
  image: article.heroImage,
}));

export function getLaunchArticleSpec(slug: string): LaunchArticleSpec | undefined {
  return launchArticleSpecs.find((article) => article.slug === slug);
}

export function buildLaunchArticleTemplate(slug: string, allRobots: ArticleRobotCard[]): ArticleBlocksTemplateData {
  const spec = getLaunchArticleSpec(slug);
  if (!spec) throw new Error(`Unknown launch article slug: ${slug}`);
  const robots = spec.robotSlugs
    .map((robotSlug) => allRobots.find((robot) => robot.slug === robotSlug))
    .filter((robot): robot is ArticleRobotCard => Boolean(robot));
  const relatedCards = launchArticleCards.filter((card) => card.href !== `/articles/${spec.slug}/`).slice(0, 4);
  const relatedArticles: HomeCardsBlock = {
    title: 'Читайте также в Блоге Кибер Гоши',
    description: 'Связанные материалы помогают выбрать гуманоида под площадку, сценарий и бюджет.',
    cards: relatedCards,
  };
  const relatedCompilations: HomeCardsBlock = {
    ...homeCompilations,
    title: 'Подборки по теме',
    description: 'Начните с живой подборки роботов-гуманоидов и сравните модели перед заявкой.',
    cards: [humanoidCompilationCard],
  };
  return {
    seo: {
      title: spec.title,
      description: spec.description,
      canonical: `/articles/${spec.slug}/`,
      h1: spec.h1,
      primaryKeyword: spec.primaryKeyword,
      secondaryKeywords: spec.secondaryKeywords,
    },
    breadcrumbs: [
      { name: 'Главная', url: '/' },
      { name: 'Блог Кибер Гоши', url: '/articles/' },
      { name: spec.h1, url: `/articles/${spec.slug}/` },
    ],
    blockVariants: [],
    hero: { eyebrow: 'Блог Кибер Гоши', lead: spec.heroLead, image: spec.heroImage },
    aiSummary: spec.aiSummary,
    gosha: { ...homeGosha, text: spec.goshaText },
    finalCta: homeRobotCardFinalCta,
    relatedArticles,
    relatedCompilations,
    robots,
    faq: { title: 'Вопросы и ответы', items: spec.faq },
    articleContent: spec.content,
  };
}
